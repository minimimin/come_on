-- 10CM 이하 물고기는 10으로 취급
WITH MAKE_TEN AS (
    SELECT ID, FISH_TYPE,
        CASE 
            WHEN LENGTH IS NULL THEN 10
            ELSE LENGTH
        END FISH_LENGTH,
        TIME
    FROM FISH_INFO
)

SELECT COUNT(ID) AS FISH_COUNT, MAX(FISH_LENGTH) AS MAX_LENGTH, FISH_TYPE AS FISH_TYPE
FROM MAKE_TEN
GROUP BY FISH_TYPE
HAVING AVG(FISH_LENGTH) >= 33
ORDER BY FISH_TYPE